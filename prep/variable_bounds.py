#!/usr/bin/env python3
"""Lower bounds for the number of variables in a basis of each variety, with a witness table each.

    python3 prep/variable_bounds.py        (writes data/variable-bounds-v1.json)

If a table T is not in a variety V but every subsemigroup of T generated by at most k elements is, then T satisfies
every identity of V in at most k variables (an assignment of k variables only reaches the subsemigroup the values
generate), so no list of identities in k variables defines V. The witnesses are searched among all tables of
orders one to six and their transposes; the subsemigroups are identified up to isomorphism with tables of the pool,
whose membership in V is known from the rows. check_data.py repeats the check for every witness.
"""
import itertools
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import census as C  # noqa: E402


def main():
    canon = {}
    for i in range(C.P):
        canon.setdefault(C.canonical_table(C.model_table(i)), i)
    memo = {}

    def pool_index(T, elements):
        sub = C.subtable(T, elements)
        key = sub.tobytes() + bytes([len(elements)])
        if key not in memo:
            memo[key] = canon[C.canonical_table(sub)]
        return memo[key]

    # SUB[k][i]: the pool tables isomorphic to the subsemigroups of table i generated by at most k elements
    SUB = {k: [] for k in range(1, 6)}
    for i in range(C.P):
        T = C.model_table(i)
        n = T.shape[0]
        found = {k: set() for k in range(1, 6)}
        seen = {}
        for r in range(1, min(n, 5) + 1):
            for gens in itertools.combinations(range(n), r):
                elements = C.generated(T, gens)
                if elements not in seen:
                    seen[elements] = pool_index(T, elements)
                for k in range(r, 6):
                    found[k].add(seen[elements])
        for k in range(1, 6):
            SUB[k].append(np.array(sorted(found[k]), dtype=np.int64))
        if i % 8000 == 0:
            C.log(f"subsemigroups {i:,}")

    out = []
    for v, var in enumerate(C.VARIETIES):
        row = var["row"]
        bound, witness, subs = 1, None, None
        for k in range(1, 6):
            outside = [i for i in np.nonzero(~row)[0] if row[SUB[k][i]].all()]
            if not outside:
                break
            bound = k + 1
            witness = min(outside, key=lambda i: C.MODELS[i])
            subs = SUB[k][witness]
        entry = {"variety": var["slug"], "generator": C.LABELS[var["gens"][0]], "lower_bound": bound}
        if witness is not None:
            entry.update({"witness": C.LABELS[witness], "k": bound - 1,
                          "subsemigroups": [C.LABELS[j] for j in subs]})
        out.append(entry)
    path = os.path.join(C.DATA, "variable-bounds-v1.json")
    with open(path, "w", encoding="utf-8") as handle:
        json.dump({"record_type": "variable_lower_bounds", "pool": "bases-min, data/order6-lower-order-20261001",
                   "bounds": out}, handle, separators=(",", ":"))
        handle.write("\n")
    from collections import Counter
    print(f"wrote {path}: {Counter(e['lower_bound'] for e in out)}")


if __name__ == "__main__":
    main()
