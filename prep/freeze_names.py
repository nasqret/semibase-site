#!/usr/bin/env python3
"""Write data/variety-names-v1.json, the frozen list of the names of the varieties (names.html), once.

    python3 prep/freeze_names.py

The names follow from a rule and do not change, so this script ran once, on 30 October 2026, when version 1 was
fixed. Run again, it writes nothing: it compares the names computed from the data with the file and reports any
difference. build.py makes the same comparison and stops on a difference.
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import census as C  # noqa: E402

PATH = os.path.join(C.DATA, "variety-names-v1.json")
HEADER = {
    "record_type": "semigroup_variety_names",
    "version": 1,
    "date": "2026-10-30",
    "scope": "every variety generated by a semigroup of order at most six",
    "rule": "V[n,k] is the variety generated by the semigroup [n,k] = SmallSemigroup(n,k) of GAP Smallsemi, and "
            "V[n,k]^op the variety generated by its opposite semigroup, with the transposed table. A variety is "
            "named after the least triple (n,k,o) whose semigroup generates it, o = 0 for [n,k] and o = 1 for its "
            "opposite, triples compared by n, then by k, then by o. Names never change.",
    "tables": "MultiplicationTable(SmallSemigroup(n,k)) of Smallsemi 0.7.2, elements numbered from 1: row i, "
              "column j holds the product of the elements i and j",
    "fields": {
        "varieties": "the names in their order, the order of their triples; for each, the triple of its generator, "
                     "the name of its dual, whether it has a finite basis, and the table of its generator "
                     "(transposed when o = 1)",
        "semigroups": "for every semigroup [n,k] of order at most six, keyed n-k: the names of the varieties "
                      "generated by its table and by the transposed table",
        "legacy": "the names V[k] of the first release (2 October 2026), after the least generator of order six "
                  "among the Smallsemi tables, with the names that replace them",
    },
    "url": "https://nasqret.github.io/semibase-site/names.html",
}


def dump(record):
    """JSON with one entry per line, so that the file reads and compares well."""
    head = json.dumps(HEADER, ensure_ascii=False, indent=1)[:-2]
    parts = [head + ","]
    compact = dict(separators=(",", ":"), ensure_ascii=False)
    lines = [json.dumps(e, **compact) for e in record["varieties"]]
    parts.append(' "varieties": [\n  ' + ",\n  ".join(lines) + "\n ],")
    for key in ("semigroups", "legacy"):
        lines = [f"{json.dumps(k)}:{json.dumps(v, **compact)}" for k, v in record[key].items()]
        parts.append(f' "{key}": {{\n  ' + ",\n  ".join(lines) + "\n }" + ("," if key == "semigroups" else ""))
    return "\n".join(parts) + "\n}\n"


def main():
    record = C.name_registry()
    if os.path.exists(PATH):
        with open(PATH, encoding="utf-8") as handle:
            frozen = json.load(handle)
        differ = [key for key in record if frozen[key] != record[key]]
        print(f"{PATH} exists; " + (f"the computed names differ in: {', '.join(differ)}" if differ else
                                     "the computed names are equal to it"))
        sys.exit(1 if differ else 0)
    text = dump(record)
    assert {key: value for key, value in json.loads(text).items() if key in record} == record
    with open(PATH, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {PATH}: {len(record['varieties'])} names, {len(record['semigroups'])} semigroups, "
          f"{len(record['legacy'])} names of the first release")


if __name__ == "__main__":
    main()
