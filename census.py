log("varieties ...")


def model_row(i):
    n, k, o = MODELS[i]
    if (n, k) not in CLASS_BASIS:
        return None
    row = ROW[CLASS_BASIS[(n, k)]]
    return row[OPI] if o else row


_groups = {}
for i in range(P):
    row = model_row(i)
    if row is not None:
        assert row[i], MODELS[i]                    # every table lies in the variety it generates
        _groups.setdefault(row.tobytes(), []).append(i)
VARIETIES = []
for gens in sorted(_groups.values(), key=lambda g: min(MODELS[i] for i in g)):
    gens.sort(key=lambda i: MODELS[i])
    n, k, o = MODELS[gens[0]]
    slug = (str(k) if n == 6 else f"{n}-{k}") + ("-op" if o else "")
    VARIETIES.append({"gens": gens, "name": (n, k, o), "slug": slug,
                      "label": f"V[{n}, {k}]" + ("ᵒᵖ" if o else ""), "row": model_row(gens[0])})
MODEL_VAR = {i: v for v, var in enumerate(VARIETIES) for i in var["gens"]}
_by_row = {var["row"].tobytes(): v for v, var in enumerate(VARIETIES)}
for var in VARIETIES:
    var["dual"] = _by_row[var["row"][OPI].tobytes()]
    var["self_dual"] = VARIETIES[var["dual"]] is var
SLUG = {var["slug"]: v for v, var in enumerate(VARIETIES)}
CLASS_VAR = {key: MODEL_VAR[model_index(*key, 0)] for key in CLASS_BASIS}
CLASS_VAR_OP = {key: MODEL_VAR[model_index(*key, 1)] for key in CLASS_BASIS}
NV = len(VARIETIES)

# Inclusion: V lies in W exactly when the generator of V satisfies the basis of W.
GEN = np.array([var["gens"][0] for var in VARIETIES])
ROWS = np.stack([var["row"] for var in VARIETIES])               # (NV, P)
INC = ROWS[:, GEN].T.copy()                                       # INC[a, b]: V_a lies in V_b
assert INC.diagonal().all()
STRICT = INC & ~np.eye(NV, dtype=bool)
assert not (STRICT & STRICT.T).any()                              # distinct varieties: no two contain each other
UP, DOWN = {v: [] for v in range(NV)}, {v: [] for v in range(NV)}
for a in range(NV):
    for b in np.nonzero(STRICT[a])[0]:
        if not (STRICT[a] & STRICT[:, b]).any():                  # nothing strictly between
            UP[a].append(int(b))
            DOWN[int(b)].append(a)


# The semigroups up to isomorphism: every table, and the transpose of a class that is not self-dual.
SEMIGROUPS = [(n, k, o) for (n, k) in CLASSES for o in (0, 1) if o == 0 or not SELF_DUAL[(n, k)]]
SG_INDEX = np.array([model_index(*s) for s in SEMIGROUPS])


def members(v):
    """The semigroups of orders one to six, up to isomorphism, in the variety V_v."""
    return [SEMIGROUPS[j] for j in np.nonzero(VARIETIES[v]["row"][SG_INDEX])[0]]


def generators(v):
    """The semigroups, up to isomorphism, that generate the variety V_v."""
    gens = np.zeros(P, dtype=bool)
    gens[VARIETIES[v]["gens"]] = True
    return [SEMIGROUPS[j] for j in np.nonzero(gens[SG_INDEX])[0]]


# ------------------------------------------------------------------ names

# Every variety generated by a semigroup of order at most six has a name (names.html): V[n,k] when the least model
# (n, k, o) that generates it has o = 0, V[n,k]^op when o = 1, models compared by n, then k, then o. The finitely
# based ones are the varieties above, named so by construction. Each of the four nonfinitely based classes is
# self-dual and generates a variety that no other semigroup of order at most six generates: a variety without a
# finite basis is none of the above, and identities separate the four (check_data.py). data/variety-names-v1.json
# fixes the names; build.py stops if they ever differ from it.
assert all(SELF_DUAL[(6, k)] for k in NONFINITE)
# x² ≈ x³, xyx ≈ x²yx and x²y² ≈ xy²x: each pair of the four nonfinitely based classes differs on one of them.
NONFINITE_SEPARATION = [{"lhs": [0, 0], "rhs": [0, 0, 0]}, {"lhs": [0, 1, 0], "rhs": [0, 0, 1, 0]},
                        {"lhs": [0, 0, 1, 1], "rhs": [0, 1, 1, 0]}]


def ascii_name(n, k, o=0):
    return f"V[{n},{k}]" + ("^op" if o else "")


NAMES = sorted([{"model": var["name"], "slug": var["slug"], "label": var["label"], "variety": v,
                 "dual": VARIETIES[var["dual"]]["name"], "finite": True} for v, var in enumerate(VARIETIES)] +
               [{"model": (6, k, 0), "slug": str(k), "label": f"V[6, {k}]", "variety": None, "dual": (6, k, 0),
                 "finite": False} for k in NONFINITE], key=lambda e: e["model"])


def model_name(n, k, o):
    """The name of the variety that the table of [n, k] (o = 0) or its transpose (o = 1) generates."""
    if (n, k) not in CLASS_BASIS:
        return ascii_name(n, k)
    return ascii_name(*VARIETIES[MODEL_VAR[model_index(n, k, o)]]["name"])


def name_registry():
    """The content of data/variety-names-v1.json below its header: the names in their order, the names of the
    varieties of every class and of its transpose, and the names of the first release."""
    varieties = []
    for e in NAMES:
        n, k, o = e["model"]
        T = np.array(TABLE[(n, k)])
        varieties.append({"name": ascii_name(n, k, o), "generator": [n, k, o], "dual": ascii_name(*e["dual"]),
                          "finitely_based": e["finite"], "table": (T.T if o else T).tolist()})
    semigroups = {f"{n}-{k}": [model_name(n, k, 0), model_name(n, k, 1)] for (n, k) in CLASSES}
    legacy = {}
    for var in VARIETIES:
        reps = [MODELS[i][1] for i in var["gens"] if MODELS[i][0] == 6 and MODELS[i][2] == 0]
        if reps:
            legacy[min(reps)] = ascii_name(*var["name"])
    return {"varieties": varieties, "semigroups": semigroups,
            "legacy": {f"V[{k}]": name for k, name in sorted(legacy.items())}}


log(f"{len(CLASSES):,} classes, {P:,} tables in the pool, {NV} varieties")
