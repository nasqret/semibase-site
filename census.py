"""The data of the census: the semigroups of orders one to six, their certified bases, the satisfaction rows of the
bases over all tables and their transposes, and the varieties that the tables generate.

Imported by build.py, check_data.py and the scripts in prep/. Everything is computed from the files in data/ and
from the catalogue of order six in a checkout of semibase-order6 (SEMIBASE_REPO, default ../semibase-order6).

Classes are pairs (n, k): the semigroup [n, k], number k of order n in GAP Smallsemi, which lists the semigroups up
to isomorphism and anti-isomorphism. A model is a triple (n, k, o): the table of [n, k] when o = 0, its transpose
(the opposite semigroup) when o = 1. The pool of bases-min holds every model once, except that a table equal to its
transpose is not repeated. A row is a boolean array over the pool: the tables in which a basis holds.

The variety generated by a finitely based model is known exactly from its row: a table lies in it if and only if
it satisfies a basis of it, and every class has a basis certified in Lean (read backwards for a transpose). Two
models generate the same variety exactly when their rows are equal, and one variety lies in another exactly when the
generator of the first satisfies the basis of the second. So the varieties and their order are decided, not
estimated.
"""
