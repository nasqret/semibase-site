# ------------------------------------------------------------------ identities


def reverse(e):
    return {"lhs": e["lhs"][::-1], "rhs": e["rhs"][::-1]}


def oriented(ids, o):
    return [reverse(e) for e in ids] if o else [{"lhs": e["lhs"], "rhs": e["rhs"]} for e in ids]


def nvars(ids):
    """The largest number of distinct variables in one identity: what it costs to check the identities."""
    return max(len(set(e["lhs"] + e["rhs"])) for e in ids)


def size(e):
    return len(e["lhs"]) + len(e["rhs"])


def canonical_identity(e):
    best = None
    for a, b in ((e["lhs"], e["rhs"]), (e["rhs"], e["lhs"])):
        names = {}
        for v in a + b:
            names.setdefault(v, len(names))
        form = (tuple(names[v] for v in a), tuple(names[v] for v in b))
        best = form if best is None or form < best else best
    return best


def canonical_basis(ids):
    return tuple(sorted(canonical_identity(e) for e in ids))


def satisfied(identities, tables):
    """For a stack of 0-based tables of one order, shape (M, n, n): which satisfy every identity."""
    M, n, _ = tables.shape
    alive = np.ones(M, dtype=bool)
    every = np.arange(M)
    for e in sorted(identities, key=lambda e: (len(set(e["lhs"] + e["rhs"])), size(e))):
        idx = every[alive]
        if not len(idx):
            break
        variables = sorted(set(e["lhs"] + e["rhs"]))
        pos = {v: i for i, v in enumerate(variables)}
        A = np.indices((n,) * len(variables), dtype=np.int8).reshape(len(variables), -1)
        chunk = max(1, int(2e7 // A.shape[1]))
        good = np.ones(len(idx), dtype=bool)
        for start in range(0, len(idx), chunk):
            part = idx[start:start + chunk]
            T = tables[part]
            r = np.arange(len(part))[:, None]

            def value(word):
                out = np.broadcast_to(A[pos[word[0]]], (len(part), A.shape[1])).copy()
                for letter in word[1:]:
                    out = T[r, out, A[pos[letter]][None, :]]
                return out
            good[start:start + chunk] = (value(e["lhs"]) == value(e["rhs"])).all(axis=1)
        alive[idx[~good]] = False
    return alive


_perms = {}


def canonical_table(table):
    """A key of a 0-based table that is equal exactly for isomorphic semigroups: its least relabelling."""
    T = np.asarray(table, dtype=np.int8)
    n = T.shape[0]
    if n not in _perms:
        P = np.array(list(itertools.permutations(range(n))), dtype=np.int8)
        _perms[n] = (P, np.argsort(P, axis=1).astype(np.int8))
    P, Q = _perms[n]
    relabelled = np.take_along_axis(Q[:, None, :].repeat(n, 1),
                                    T[P[:, :, None], P[:, None, :]].astype(np.int64), axis=2)
    flat = relabelled.reshape(len(P), -1)
    return bytes([n]) + flat[np.lexsort(flat.T[::-1])[0]].tobytes()


def generated(table, gens):
    """The subsemigroup of a 0-based table generated by some elements, as a sorted tuple."""
    found, frontier = set(gens), list(gens)
    while frontier:
        new = []
        for a in list(found):
            for b in frontier:
                for c in (int(table[a][b]), int(table[b][a])):
                    if c not in found:
                        found.add(c)
                        new.append(c)
        frontier = new
    return tuple(sorted(found))


def subtable(table, elements):
    pos = {e: i for i, e in enumerate(elements)}
    return np.array([[pos[int(table[a][b])] for b in elements] for a in elements], dtype=np.int8)


