def _model(label):
    number = int(label.split(":")[1])
    if number < 1000000:
        return (6, number % 100000, number // 100000)
    n, rest = divmod(number, 1000000)
    return (n, rest % 500000, rest // 500000)


MODELS = [_model(label) for label in LABELS]
MINDEX = {m: i for i, m in enumerate(MODELS)}
OPI = np.array([MINDEX.get((n, k, 1 - o), i) for i, (n, k, o) in enumerate(MODELS)])   # transpose in the pool


def model_index(n, k, o=0):
    """The pool index of a model; a table equal to its transpose is pooled once."""
    return MINDEX.get((n, k, o), MINDEX[(n, k, 0)])


def bits(hexstring):
    value = int(hexstring, 16)
    return np.unpackbits(np.frombuffer(value.to_bytes((P + 7) // 8, "little"), dtype=np.uint8),
                         bitorder="little")[:P].astype(bool)


ROW = {}
for r in _rows:
    for basis_id, hexstring in r["rows"].items():
        ROW[basis_id] = bits(hexstring)
assert set(CLASS_BASIS.values()) <= set(ROW)


def model_table(i):
    n, k, o = MODELS[i]
    T = np.array(TABLE[(n, k)], dtype=np.int8) - 1
    return T.T.copy() if o else T


