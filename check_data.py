#!/usr/bin/env python3
"""Check the data the census site shows against the Cayley tables, by evaluation.

1. Every finitely based class of order one to six satisfies its certified basis, and its transpose satisfies the
   basis read backwards (identities with at most BUDGET assignments of their variables; others in nilpotent
   tables when both sides vanish).
2. For a random sample of pairs (variety, table of the pool), the table lies in the variety by the rows exactly when
   it satisfies the basis of the variety in the fewest variables.
3. No table of a nonfinitely based class, nor its transpose, lies in any variety.
4. Every basis found by the search for few variables holds in exactly the tables of the pool that the variety
   contains, and in its generator.
5. Every lower bound on the number of variables has a valid witness: a table outside the variety whose subsemigroups
   generated by k elements lie in it, or a semigroup outside the variety that satisfies every identity of the
   variety in k variables (it satisfies the rules of a complete rewriting system of the free object on k
   generators, recomputed here).
6. The names of the database of Araújo et al. belong to the varieties of their generators.
7. The names of the varieties (data/variety-names-v1.json), by evaluating the certified bases, without the rows: no
   two tables of the census are isomorphic or anti-isomorphic, and a class is self-dual exactly when its transpose is
   a renumbering of it; every table and its transpose generate the varieties named for them (each lies in the
   variety of the generator of the name and the generator lies in its variety); the finitely based varieties are
   pairwise distinct, and the generator of each name is the least table that generates it; the duals are right; and
   three identities tell apart the four nonfinitely based classes, which are self-dual.

The checks are independent of Lean and of Vampire: they only evaluate identities in tables.
"""
import itertools
import json
import os
import random
import sys
from collections import defaultdict

import numpy as np

import census as C

sys.path.insert(0, os.path.join(C.HERE, "prep"))
from fewvars import free_object, identities_of  # noqa: E402

BUDGET = 3_000_000     # the most assignments evaluated for one identity in one table


def nil_class(T):
    n = len(T)
    zero = [z for z in range(n) if all(T[z][x] == z == T[x][z] for x in range(n))]
    if not zero or n == 1:
        return 0
    power, degree = set(range(n)), 1
    while len(power) > 1:
        following = {int(T[a][b]) for a in power for b in range(n)}
        if following == power:
            return 0
        power, degree = following, degree + 1
    return degree if power == {zero[0]} else 0


def holds(T, e, nil=0):
    """True or False, or None when the identity has too many variables to evaluate."""
    T = np.asarray(T)
    n = T.shape[0]
    variables = sorted(set(e["lhs"]) | set(e["rhs"]))
    if nil and len(e["lhs"]) >= nil and len(e["rhs"]) >= nil:
        return True
    if n ** len(variables) > BUDGET:
        return None
    index = {v: i for i, v in enumerate(variables)}
    A = np.indices((n,) * len(variables)).reshape(len(variables), -1)

    def value(word):
        out = A[index[word[0]]]
        for letter in word[1:]:
            out = T[out, A[index[letter]]]
        return out

    return bool(np.array_equal(value(e["lhs"]), value(e["rhs"])))


def satisfies(T, identities):
    nil = nil_class(T)
    results = [holds(T, e, nil) for e in identities]
    if False in results:
        return False
    return None if None in results else True


def within(T, identities):
    """Whether a 0-based table satisfies every identity: the cheapest first, stopping at the first that fails; None
    when one is too large to evaluate."""
    nil = nil_class(T)
    unknown = False
    for e in sorted(identities, key=lambda e: (len(set(e["lhs"] + e["rhs"])), size(e))):
        result = holds(T, e, nil)
        if result is False:
            return False
        unknown = unknown or result is None
    return None if unknown else True


def size(e):
    return len(e["lhs"]) + len(e["rhs"])


def check_names():
    failures = []
    registry = json.load(open(os.path.join(C.DATA, "variety-names-v1.json"), encoding="utf-8"))

    # Classes: pairwise neither isomorphic nor anti-isomorphic; self-dual exactly when the transpose is a renumbering.
    forms = {key: C.canonical_table(np.array(C.TABLE[key]) - 1) for key in C.CLASSES}
    all_forms = set(forms.values())
    if len(all_forms) != len(forms):
        failures.append(("names", "isomorphic classes"))
    for key in C.CLASSES:
        transposed = C.canonical_table((np.array(C.TABLE[key]) - 1).T)
        if (transposed == forms[key]) != C.SELF_DUAL[key] or (not C.SELF_DUAL[key] and transposed in all_forms):
            failures.append(("names", "self-duality", key))

    # The basis of a table: the certified basis of its class, read backwards for a transpose.
    def basis(n, k, o):
        return C.oriented(C.BASIS[C.CLASS_BASIS[(n, k)]], o)

    def table(n, k, o):
        T = np.array(C.TABLE[(n, k)], dtype=np.int8) - 1
        return T.T.copy() if o else T

    entries = {e["name"]: e for e in registry["varieties"]}
    finite = [e for e in registry["varieties"] if e["finitely_based"]]
    for e in registry["varieties"]:
        n, k, o = e["generator"]
        if e["table"] != (table(n, k, o) + 1).tolist() or e["name"] != C.ascii_name(n, k, o):
            failures.append(("names", "generator", e["name"]))

    # Every table generates the variety named for it: it satisfies the basis of the generator of the name, and the
    # generator satisfies its basis. The generator of a name is the least of these tables.
    named = defaultdict(list)                     # name -> the triples whose tables are named for it
    for key, (name0, name1) in registry["semigroups"].items():
        n, k = map(int, key.split("-"))
        named[name0].append((n, k, 0))
        if not C.SELF_DUAL[(n, k)]:
            named[name1].append((n, k, 1))
        elif name1 != name0:
            failures.append(("names", "self-dual class with two names", key))
    if set(named) != set(entries):
        failures.append(("names", "names without tables, or tables without names"))
    tables = 0
    for name, triples in named.items():
        e = entries[name]
        g = tuple(e["generator"])
        if min(triples) != g:
            failures.append(("names", "not the least generator", name))
        if not e["finitely_based"]:
            if triples != [g]:
                failures.append(("names", "nonfinitely based", name))
            continue
        G, B = table(*g), basis(*g)
        for t in triples:
            tables += 1
            if within(table(*t), B) is not True or within(G, basis(*t)) is not True:
                failures.append(("names", "not generating its variety", name, t))

    # The finitely based varieties are pairwise distinct: of two generators, one lies outside the variety of the
    # other. Each variety is tested with its certified basis in the fewest variables, a basis of it by the above.
    def cost(ids):
        return (max(len(set(e["lhs"] + e["rhs"])) for e in ids), sum(size(e) for e in ids))
    cheap = {e["name"]: min((basis(*t) for t in named[e["name"]]), key=cost) for e in finite}
    gens = {e["name"]: table(*e["generator"]) for e in finite}
    for a, b in itertools.combinations([e["name"] for e in finite], 2):
        if within(gens[a], cheap[b]) is not False and within(gens[b], cheap[a]) is not False:
            failures.append(("names", "equal varieties", a, b))

    # Duals: the dual of a name is the name of the variety of the transposed generator.
    for e in registry["varieties"]:
        n, k, o = e["generator"]
        if e["dual"] != registry["semigroups"][f"{n}-{k}"][1 - o]:
            failures.append(("names", "dual", e["name"]))

    # The four nonfinitely based classes: self-dual, and separated pairwise by three identities.
    results = [[holds(np.array(C.TABLE[(6, k)]) - 1, e) for k in C.NONFINITE] for e in C.NONFINITE_SEPARATION]
    for a, b in itertools.combinations(range(len(C.NONFINITE)), 2):
        if not any(r[a] != r[b] for r in results):
            failures.append(("names", "nonfinitely based not separated", C.NONFINITE[a], C.NONFINITE[b]))
    if not all(C.SELF_DUAL[(6, k)] for k in C.NONFINITE):
        failures.append(("names", "nonfinitely based not self-dual"))

    print(f"7. names: {len(registry['varieties'])} names; {tables:,} semigroups, up to isomorphism, generate the "
          f"varieties named for them; {len(finite)} finitely based varieties, pairwise distinct; the four others "
          f"separated; {len(failures)} failures")
    return failures


def main():
    failures, partial = [], 0

    # 1. every class and its transpose satisfy the certified basis
    for key, b in C.CLASS_BASIS.items():
        T = np.array(C.TABLE[key]) - 1
        for o in (0, 1):
            if o and C.SELF_DUAL[key]:
                continue
            result = satisfies(T.T if o else T, C.oriented(C.BASIS[b], o))
            if result is False:
                failures.append(("certified", key, o))
            elif result is None:
                partial += 1
    print(f"1. {len(C.CLASS_BASIS):,} classes and their transposes: {len(failures)} fail their certified basis, "
          f"{partial} checks partial (identities with more than {BUDGET:,} assignments)")

    # 2. rows against evaluation, on a sample, with the basis in the fewest variables shown on the pages
    sys.argv = sys.argv[:1]
    import build as B
    random.seed(20261028)
    disagree = undecided = 0
    for _ in range(20000):
        v = random.randrange(C.NV)
        i = random.randrange(C.P)
        result = satisfies(C.model_table(i), B.FEWEST_VARS[v]["identities"])
        if result is None:
            undecided += 1
        elif result != bool(C.VARIETIES[v]["row"][i]):
            disagree += 1
            failures.append(("row", C.VARIETIES[v]["slug"], C.LABELS[i]))
    print(f"2. 20,000 sampled pairs (variety, table): {disagree} disagree with the rows, {undecided} undecided")

    # 3. the nonfinitely based tables lie in no variety
    inside = [(k, o) for k in C.NONFINITE for o in (0, 1) if C.ROWS[:, C.model_index(6, k, o)].any()]
    print(f"3. nonfinitely based tables inside a variety: {len(inside)}")
    failures += [("nonfinite", x) for x in inside]

    # 4. the bases of the search hold in exactly the tables of the variety
    by_order = {}
    for i, (n, k, o) in enumerate(C.MODELS):
        by_order.setdefault(n, []).append(i)
    stacks = {n: np.stack([C.model_table(i) for i in members]) for n, members in by_order.items()}
    checked = 0
    for v in range(C.NV):
        for c in B.CANDIDATES[v]:
            if c["kind"] not in ("search", "reduce"):
                continue
            row = np.zeros(C.P, dtype=bool)
            for n, members in by_order.items():
                row[members] = C.satisfied(c["identities"], stacks[n])
            if not np.array_equal(row, C.VARIETIES[v]["row"]):
                failures.append(("search row", C.VARIETIES[v]["slug"]))
            checked += 1
    print(f"4. {checked} bases of the search and of the reduction hold in exactly the tables of their varieties")

    # 5. the witnesses of the lower bounds
    pool_ok = model_ok = 0
    for v in range(C.NV):
        var = C.VARIETIES[v]
        bound = B.BOUND_INFO[v]
        # the certified basis of the variety in the fewest variables (any certified basis is a basis of it)
        basis = min((c["identities"] for c in B.CANDIDATES[v] if c["kind"] == "certified"),
                    key=lambda ids: (C.nvars(ids), len(ids)))
        if bound.get("witness"):
            i = C.LABELS.index(bound["witness"])
            T, k = C.model_table(i), bound["k"]
            ok = not var["row"][i] and satisfies(T, basis) is not True
            for r in range(1, k + 1):
                for gens in itertools.combinations(range(len(T)), r):
                    sub = C.subtable(T, C.generated(T, gens))
                    ok = ok and satisfies(sub, basis) is True
            pool_ok += ok
            if not ok:
                failures.append(("pool witness", var["slug"]))
        if bound.get("model"):
            T, k = np.array(bound["model"]), bound["k"]
            n, kk, o = C.MODELS[var["gens"][0]]
            G = C.model_table(var["gens"][0])
            free = free_object(G.tolist(), k)
            rules = [{"lhs": list(a), "rhs": list(b)} for a, b in identities_of(free[1])]
            violated = bound["violates"]
            ok = (all(T[T[a, b], c] == T[a, T[b, c]] for a in range(len(T)) for b in range(len(T))
                      for c in range(len(T)))
                  and satisfies(T, rules) is True and holds(G, violated) is True and holds(T, violated) is False)
            model_ok += ok
            if not ok:
                failures.append(("countermodel", var["slug"]))
    print(f"5. lower bounds: {pool_ok} witnesses among the tables and {model_ok} countermodels check")

    # 6. the names of the database
    wrong = [e["name"] for v, e in B.SGV.items() if C.MODEL_VAR[C.LABELS.index(e["generator"])] != v]
    print(f"6. {len(B.SGV)} names of the database, {len(wrong)} wrong")
    failures += wrong

    # 7. the names
    failures += check_names()

    for failure in failures[:20]:
        print("   FAIL", failure)
    if failures:
        sys.exit(1)


if __name__ == "__main__":
    main()
